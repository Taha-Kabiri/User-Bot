// ---- تشخیص لحن متن ----
export function detectTone(text) {
  if (!text || !text.trim()) return { tone: 'neutral', intensity: 0 };

  let bestTone = 'neutral';
  let bestScore = 0;

  const lowerText = text.toLowerCase();
  const totalWords = lowerText.split(/\s+/).length || 1;

  for (const [tone, regex] of Object.entries(TONE_PATTERNS)) {
    const matches = lowerText.match(regex) || [];
    if (matches.length > 0) {
      const intensity = Math.min(matches.length / totalWords * 10, 1.0);
      if (intensity > bestScore || (intensity === bestScore && bestTone === 'neutral')) {
        bestScore = intensity;
        bestTone = tone;
      }
    }
  }

  return { tone: bestTone, intensity: Number(bestScore.toFixed(2)) };
}

// ---- تشخیص نوع فایل ----
export function detectFileTone(fileType, fileName) {
  if (fileType.includes('audio') || fileType.includes('music')) return 'music';
  if (fileType.includes('image')) return 'image';
  if (fileType.includes('video')) return 'video';
  return 'file';
}
